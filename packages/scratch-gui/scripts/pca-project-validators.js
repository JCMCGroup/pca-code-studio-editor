// PCA patch: precompile scratch-parser's project and sprite schemas.
//
// scratch-parser's lib/validate.js compiles its JSON schemas with ajv 6 in the
// browser each time a project or sprite is loaded, and ajv compiles with
// `new Function`, which a Content-Security-Policy without 'unsafe-eval'
// refuses. This turns the same schemas into plain JavaScript with ajv 8's
// standalone code generator at build time. src/lib/pca/scratch-parser-validate.js
// uses the output in place of lib/validate.js (see webpack.config.js).
//
// test/unit/pca/scratch-parser-validate.test.js checks the generated validators
// reach the same verdicts as scratch-parser's own over the project fixtures.
const fs = require('fs');
const path = require('path');

const Ajv = require('ajv').default;
const standaloneCode = require('ajv/dist/standalone').default;

const SCHEMA_DIR = path.join(path.dirname(require.resolve('scratch-parser/package.json')), 'lib');
const OUTPUT = path.join(__dirname, '..', 'src', 'generated', 'project-validators.cjs');

const DEFINITIONS = ['sb2_definitions', 'sb3_definitions'];
const VALIDATORS = {
    sb2: 'sb2_schema',
    sb3: 'sb3_schema',
    sprite2: 'sprite2_schema',
    sprite3: 'sprite3_schema'
};

/**
 * Load one of scratch-parser's schemas in the form ajv 8 accepts. They name
 * themselves with the draft-04 `id` keyword and declare a `$schema` URI that
 * ajv 8 does not recognise; ajv 6 applied its default draft-07 rules to them,
 * as ajv 8 does once those two are adjusted.
 * @param {string} name Schema file name without the extension.
 * @returns {object} The schema.
 */
const loadSchema = name => {
    const schema = JSON.parse(fs.readFileSync(path.join(SCHEMA_DIR, `${name}.json`), 'utf8'));
    if (typeof schema.id === 'string') {
        schema.$id = schema.id;
        delete schema.id;
    }
    delete schema.$schema;
    return schema;
};

/**
 * Generate src/generated/project-validators.cjs, exporting one validator per
 * key of VALIDATORS. The file is only rewritten when its content changes.
 * @returns {string} Path of the generated file.
 */
const buildProjectValidators = () => {
    const ajv = new Ajv({
        code: {source: true},
        // ajv 6 ignored keywords it did not know and built patterns without the `u` flag.
        strict: false,
        unicodeRegExp: false
    });
    DEFINITIONS.forEach(name => ajv.addSchema(loadSchema(name)));
    const refs = {};
    for (const [key, name] of Object.entries(VALIDATORS)) {
        const schema = loadSchema(name);
        ajv.addSchema(schema);
        refs[key] = schema.$id;
    }

    const code = `// Generated by scripts/pca-project-validators.js. Do not edit.\n${standaloneCode(ajv, refs)}\n`;
    if (/new Function|\beval\(/.test(code)) {
        throw new Error('Generated project validators must not compile code at run time');
    }
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : null;
    if (current !== code) {
        fs.mkdirSync(path.dirname(OUTPUT), {recursive: true});
        fs.writeFileSync(OUTPUT, code);
    }
    return OUTPUT;
};

module.exports = {buildProjectValidators};

if (require.main === module) {
    console.log(`Wrote ${buildProjectValidators()}`);
}
